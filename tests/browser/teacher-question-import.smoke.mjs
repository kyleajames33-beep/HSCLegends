import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const modulePath = process.env.HSC_PLAYWRIGHT_MODULE;
const { chromium } = modulePath ? await import(pathToFileURL(modulePath).href) : await import('playwright');
const base = process.env.HSC_BASE_URL || 'http://localhost:3000';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, acceptDownloads: true });
  await page.goto(`${base}/question-import`, { waitUntil: 'networkidle' });
  const writes = []; page.on('request', request => { if (request.method() !== 'GET') writes.push(request.url()); });
  const header = 'id,stem,option_a,option_b,answer,explanation,subject,year,module,syllabus_version,source';
  const row = 'sample-1,Which gas is produced?,Hydrogen,Oxygen,B,Oxygen is produced in this synthetic example.,chemistry,12,module-5,2017,Teacher-created';
  const input = page.locator('#question-file');
  await input.setInputFiles({ name: 'questions.csv', mimeType: 'text/csv', buffer: Buffer.from(`${header}\n${row}\n`) });
  await page.getByRole('heading', { name: 'Structure checks passed' }).waitFor();
  await page.getByText('Review question 1 and answer').click();
  await page.getByText('B. Oxygen (marked correct)').waitFor();
  await page.getByText('Oxygen is produced in this synthetic example.', { exact: false }).waitFor();
  await page.getByRole('checkbox', { name: /I checked the answer/ }).check();
  await page.getByText('1 of 1 checked in this session.', { exact: false }).waitFor();
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download unreviewed draft' }).click()]);
  const raw = await readFile(await download.path(), 'utf8');
  const draft = JSON.parse(raw);
  assert.equal(draft.reviewStatus, 'unreviewed');
  assert.equal(draft.questions[0].correctIndex, 1);
  assert.equal(draft.questions[0].source, 'Teacher-created');
  await input.setInputFiles({ name: 'draft.json', mimeType: 'application/json', buffer: Buffer.from(raw) });
  await page.getByRole('heading', { name: 'Structure checks passed' }).waitFor();
  await page.getByText('0 of 1 checked in this session.', { exact: false }).waitFor();
  await input.setInputFiles({ name: 'bad.csv', mimeType: 'text/csv', buffer: Buffer.from(`${header}\n${row.replace('Hydrogen,Oxygen', 'Oxygen,Oxygen')}\n`) });
  await page.getByRole('heading', { name: 'Fix these questions' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Download unreviewed draft' }).count(), 0);
  await page.evaluate(() => {
    const original = File.prototype.text;
    File.prototype.text = function () {
      if (this.name !== 'slow.csv') return original.call(this);
      return new Promise(resolve => { globalThis.releaseSlowImport = () => original.call(this).then(resolve); });
    };
  });
  await input.setInputFiles({ name: 'slow.csv', mimeType: 'text/csv', buffer: Buffer.from(`${header}\n${row.replace('Hydrogen,Oxygen', 'Oxygen,Oxygen')}\n`) });
  await page.getByRole('status').waitFor();
  assert.match(await page.getByRole('status').innerText(), /Reading slow.csv/);
  await input.setInputFiles({ name: 'new.csv', mimeType: 'text/csv', buffer: Buffer.from(`${header}\n${row}\n`) });
  await page.getByRole('heading', { name: 'Structure checks passed' }).waitFor();
  await page.evaluate(() => globalThis.releaseSlowImport());
  await page.getByText(/questions? in new.csv/).waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Fix these questions' }).count(), 0);
  await page.getByRole('button', { name: 'Preview in solo arena' }).click();
  await page.waitForURL('**/arena?draft=1');
  await page.getByText(/Previewing 1 unreviewed teacher question/).waitFor();
  await page.getByRole('button', { name: 'ENTER ARENA' }).click();
  await page.getByRole('heading', { name: 'Which gas is produced?' }).waitFor();
  await page.getByRole('button', { name: 'A Hydrogen', exact: true }).click();
  await page.getByText('Oxygen is produced in this synthetic example.').waitFor();
  await page.waitForFunction(() => sessionStorage.getItem('hsclegends.knockout-solo.session.v1')?.includes('answer'));
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /Resume previous game/ }).click();
  await page.getByRole('button', { name: 'SEE RESULTS' }).click();
  await page.getByText('Review 1 missed answer').click();
  await page.getByText('Which gas is produced?').waitFor();
  await page.getByText('Correct: Oxygen').waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(writes, []);
  console.log('Teacher draft: local CSV, JSON round trip, invalid-row blocking and no uploads passed');
} finally { await browser.close(); }
